CREATE TABLE IF NOT EXISTS state (key TEXT PRIMARY KEY, value TEXT NOT NULL, updated INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS starts (id TEXT PRIMARY KEY, requested INTEGER NOT NULL, status TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS auth_attempts (ip TEXT PRIMARY KEY, attempts INTEGER NOT NULL, until_time INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS history (id TEXT PRIMARY KEY, run_id TEXT NOT NULL, value TEXT NOT NULL, updated INTEGER NOT NULL);
